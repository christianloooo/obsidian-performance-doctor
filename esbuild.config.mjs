import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/`;

const args = process.argv.slice(2);
const prod = args.includes('production');
const harnessCore = args.includes('--harness-core');

async function buildMain() {
  const context = await esbuild.context({
    banner: { js: banner },
    entryPoints: ['src/obsidian/main.ts'],
    bundle: true,
    external: [
      'obsidian',
      'electron',
      '@codemirror/autocomplete',
      '@codemirror/collab',
      '@codemirror/commands',
      '@codemirror/language',
      '@codemirror/lint',
      '@codemirror/search',
      '@codemirror/state',
      '@codemirror/view',
      '@lezer/common',
      '@lezer/highlight',
      '@lezer/lr',
      ...builtinModules,
    ],
    format: 'cjs',
    target: 'es2021',
    logLevel: 'info',
    sourcemap: prod ? false : 'inline',
    treeShaking: true,
    outfile: 'main.js',
    minify: prod,
  });

  if (prod) {
    await context.rebuild();
    process.exit(0);
  } else {
    await context.watch();
  }
}

async function buildHarnessCore() {
  // Pure core only — no obsidian, no electron, browser + node friendly ESM
  await esbuild.build({
    entryPoints: ['src/core/measurement.ts', 'src/core/statistics.ts', 'src/core/report.ts', 'src/core/inventory.ts'],
    bundle: true,
    // Do NOT externalize node builtins for harness so it runs in plain browser too when possible
    format: 'esm',
    target: 'es2021',
    logLevel: 'info',
    sourcemap: false,
    treeShaking: true,
    outdir: 'harness',
    outExtension: { '.js': '.js' },
    // We will name outputs carefully; esbuild will produce measurement.js etc.
    // Simpler: single entry that re-exports everything
    // Use a tiny shim entry
  });

  // Single file re-export bundle using dedicated entry
  await esbuild.build({
    entryPoints: ['src/harness-core-entry.ts'],
    bundle: true,
    format: 'esm',
    target: 'es2021',
    logLevel: 'info',
    sourcemap: false,
    treeShaking: true,
    outfile: 'harness/core.js',
    minify: prod,
  });

  console.log('Harness core bundle written to harness/core.js');
  process.exit(0);
}

if (harnessCore) {
  buildHarnessCore();
} else {
  buildMain();
}
